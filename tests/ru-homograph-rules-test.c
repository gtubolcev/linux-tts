static int failed;

static void
check (RuHomograph *h, const gchar *in, const gchar *marked, RuStressMark mark, const gchar *want)
{
  gchar *got = ru_homograph_resolve (h, in, marked, mark);

  if (g_strcmp0 (got, want) != 0)
    {
      g_print ("FAIL %s\n  got:  %s\n  want: %s\n", in, got ? got : "(null)", want ? want : "(null)");
      failed++;
    }
  g_free (got);
}

int
main (void)
{
  RuHomograph *h = ru_homograph_new ("/nonexistent", "rules", 1, 0);
  const gchar *const bad[] = { "руки | рук: <@gen", "руки", "руки | рук+: <@nope",
                               "руки | ног+: <@gen", "руки | рук+:", NULL };
  GError *error = NULL;
  GString *big;
  gchar *s;

  for (guint i = 0; i < G_N_ELEMENTS (cases); i++)
    check (h, cases[i].in, cases[i].in, RU_STRESS_PLUS, cases[i].out);

  /* the acute mark; the user's own mark kept; marks from the dictionary
   * replaced */
  check (h, "Вокруг села поля.", "Вокруг села поля.", RU_STRESS_ACUTE, "Вокруг села\xcc\x81 поля.");
  check (h, "Вокруг с+ела поля.", "Вокруг с+ела поля.", RU_STRESS_PLUS, NULL);
  check (h, "Вокруг села поля.", "Вокруг с+ела поля.", RU_STRESS_PLUS, "Вокруг сел+а поля.");
  check (h, "Вокруг села поля.", "Вокруг села поля.", RU_STRESS_NONE, NULL);
  /* garbage */
  check (h, "у \xff реки", "у \xff реки", RU_STRESS_PLUS, NULL);
  check (h, "у реки", "у реки и", RU_STRESS_PLUS, NULL);
  check (h, NULL, "у реки", RU_STRESS_PLUS, NULL);
  check (NULL, "у реки", "у реки", RU_STRESS_PLUS, NULL);
  /* long text: every sentence alone */
  big = g_string_new (NULL);
  for (int i = 0; i < 2000; i++)
    g_string_append (big, "Вокруг села поля. ");
  s = ru_homograph_resolve (h, big->str, big->str, RU_STRESS_PLUS);
  if (s == NULL || strstr (s, "Вокруг села ") != NULL)
    {
      g_print ("FAIL long text\n");
      failed++;
    }
  g_free (s);
  g_string_free (big, TRUE);
  /* rules off: nothing (no model files either) */
  ru_homograph_set_rules (h, FALSE);
  check (h, "Вокруг села поля.", "Вокруг села поля.", RU_STRESS_PLUS, NULL);
  ru_homograph_free (h);

  /* bad tables */
  for (guint i = 0; bad[i] != NULL; i++)
    {
      const gchar *one[] = { bad[i], NULL };
      RuHomoRules *r = ru_homo_rules_parse (one, &error);

      if (r != NULL)
        {
          g_print ("FAIL accepted bad rule: %s\n", bad[i]);
          failed++;
          ru_homo_rules_free (r);
        }
      g_clear_error (&error);
    }
  if (ru_homo_rules_builtin () == NULL)
    {
      g_print ("FAIL the built-in table\n");
      failed++;
    }
  g_print ("%s: %d failed\n", failed ? "FAIL" : "PASS", failed);
  return failed > 0;
}
