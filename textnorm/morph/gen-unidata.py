#!/usr/bin/python3 -I
"""gen-unidata.py > unidata.h: Unicode tables matching the oracle's Python.

Run it with the oracle's Python (3.12.3, Unicode 15.0) so str.lower(), str.isalpha() & co.
in morph.c behave exactly as in pymorphy3 there. Cased / case-ignorable (for the final-sigma
rule of str.lower()) are read back from str.lower() itself.
"""
import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if 0xD800 <= cp < 0xE000:
            ok = False
        else:
            ok = pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def emit_ranges(name, rs):
    print("static const uint32_t %s[][2] = {" % name)
    for i in range(0, len(rs), 4):
        print("\t" + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 4]))
    print("};")


def cased(c):
    return c.islower() or c.isupper() or c.istitle()


def case_ignorable(c):
    # 'A' c 'Σ' ends in final sigma if c is case-ignorable or cased; '1' c 'Σ' only if c is
    # cased and not case-ignorable
    t2 = ("A" + c + "Σ").lower()[-1] == "ς"
    t1 = ("1" + c + "Σ").lower()[-1] == "ς"
    return t2 and not t1


print("/* generated by gen-unidata.py with Python %s, Unicode %s; do not edit */"
      % (sys.version.split()[0], unicodedata.unidata_version))
emit_ranges("U_ALPHA", ranges(str.isalpha))
emit_ranges("U_LATIN", ranges(lambda c: c.isalpha() and "LATIN" in unicodedata.name(c, "")))
emit_ranges("U_PUNCT", ranges(lambda c: unicodedata.category(c)[0] == "P"))
emit_ranges("U_SPACE", ranges(str.isspace))
emit_ranges("U_CASED", ranges(cased))
emit_ranges("U_CASE_IGNORABLE", ranges(case_ignorable))

# decimal digits: runs (lo, hi, value of lo)
dec = []
for cp in range(MAX):
    if 0xD800 <= cp < 0xE000:
        continue
    d = unicodedata.decimal(chr(cp), None)
    if d is None:
        continue
    if dec and dec[-1][1] == cp - 1 and dec[-1][2] + (cp - dec[-1][0]) == d:
        dec[-1][1] = cp
    else:
        dec.append([cp, cp, d])
print("static const uint32_t U_DECIMAL[][3] = {")
for r in dec:
    print("\t{0x%X, 0x%X, %d}," % tuple(r))
print("};")

# str.lower() of single characters (U+03A3 handled by the final-sigma rule in morph.c)
low = []
for cp in range(MAX):
    if 0xD800 <= cp < 0xE000:
        continue
    c = chr(cp)
    lc = c.lower()
    if lc != c:
        if len(lc) > 3:
            sys.exit("lower() longer than 3 for U+%04X" % cp)
        low.append((cp, len(lc)) + tuple(ord(x) for x in lc) + (0,) * (3 - len(lc)))
print("static const uint32_t U_LOWER[][5] = {")
for r in low:
    print("\t{0x%X, %d, 0x%X, 0x%X, 0x%X}," % r)
print("};")
