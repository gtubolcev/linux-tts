#!/usr/bin/python3 -I
"""gen-ipa.py OUT.tsv: the IPA that eng_to_ipa gives every word latinization can look up.

latinization.py converts each Latin token with eng_to_ipa.convert() and keeps the last of
the sorted variants. A token is [a-z][a-z'-]* after lower() and "’" → "'"; eng_to_ipa
strips the trailing "'" and "-" (they are put back after the IPA), so only CMU words of
the form [a-z]([a-z'-]*[a-z])? can be found. Writes "word<TAB>ipa" lines sorted by bytes,
made by eng_to_ipa itself (run where the oracle's eng_to_ipa is installed).
"""
import re
import sqlite3
import sys
from os.path import dirname, join

import eng_to_ipa as ipa

db = sqlite3.connect(join(dirname(ipa.__file__), "resources", "CMU_dict.db"))
words = sorted({w for (w,) in db.execute("SELECT DISTINCT word FROM dictionary")
                if re.fullmatch(r"[a-z](?:[a-z'-]*[a-z])?", w)})
out = []
for i in range(0, len(words), 800):
    chunk = words[i:i + 800]
    for w, variants in zip(chunk, ipa.ipa_list(chunk, keep_punct=True), strict=True):
        top = variants[-1] if variants else ""
        assert "*" not in top and "\t" not in top and "\n" not in top, (w, top)
        assert i % 8000 or top == ipa.convert(w), (w, top)   # spot check: same as convert()
        out.append((w.encode(), top))
out.sort()
with open(sys.argv[1], "w", encoding="utf-8", newline="\n") as f:
    f.write("# eng_to_ipa %s top IPA per CMU word, generated by gen-ipa.py\n"
            % getattr(ipa, "__version__", "?"))
    for w, top in out:
        f.write("%s\t%s\n" % (w.decode(), top))
print(len(out), "words", file=sys.stderr)
