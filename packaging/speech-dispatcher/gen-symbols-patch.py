#!/usr/bin/python3 -I
"""gen-symbols-patch.py SRC_TREE OUT.patch : writes the ru-symbols-norep patch.

With punctuation mode "none" speech-dispatcher deletes every symbol of level
"some" or "most" that has no preserve flag before the text reaches the
module: "3,5%" arrives as "3,5", "2 + 2 = 4" as "2 2 4", "°C" as " C",
"opennet.ru" as "opennet ru", "км/ч" as "км ч"; emojis.dic replaces "€20"
by "евро 20" (wrong order for Russian). Preserve "norep" keeps the symbol in
the text whenever its replacement is not spoken, so the module's text
normalization reads it in context ("три целых пять десятых процента",
"двадцать евро"); at punctuation levels that reach the symbol the
replacement is read as before.

Only the Russian tables: the Russian modules normalize the text themselves.
SRC_TREE is the unpacked source (locale/ru/{symbols,emojis}.dic); the line
endings of the files (mostly CRLF) are kept.
"""
import difflib, os, sys

KEEP = set("%‰₽°№+−×÷±=<>$£€¥/*&.@_")
HEADER = """Description: ru symbols: keep %, +, =, /, °, №, € ... for the module
 With punctuation "none" speech-dispatcher deleted these symbols (level some
 or most, no preserve flag) before the module saw the text, so a module that
 normalizes the text itself read "3,5%" as "три целых пять десятых", "2 + 2 =
 4" as "два два четыре", "км/ч" as "км ч". Preserve "norep" keeps the symbol
 when its name is not spoken. emojis.dic spoke "€", "₽", "−" at level none
 ("евро 20" for "€20"); they get level all and norep like "$" in symbols.dic.
 Generated by packaging/speech-dispatcher/gen-symbols-patch.py.
Author: Grigory Tuboltsev
Forwarded: no
Last-Update: 2026-11-23
---
"""


def edit(path, emojis):
    out, sec, n = [], None, 0
    for raw in open(path, "rb").read().split(b"\n"):
        cr = raw.endswith(b"\r")
        s = raw.rstrip(b"\r").decode("utf-8")
        st = s.lstrip("﻿")
        if st.endswith(":") and "\t" not in st:
            sec = st
        c = st.split("\t")
        if sec == "symbols:" and c[0] in KEEP and len(c) >= 2:
            lvl = c[2] if len(c) > 2 and c[2] else "some"
            pres = c[3] if len(c) > 3 and not c[3].startswith("#") else ""
            if pres != "norep":
                if emojis and lvl == "none":
                    lvl = "all"
                rest = c[4:] if pres or (len(c) > 3 and c[3] == "") else c[3:]
                s = s[:len(s) - len(st)] + "\t".join([c[0], c[1], lvl, "norep"] + rest)
                n += 1
        out.append(s.encode() + (b"\r" if cr else b""))
    return b"\n".join(out), n


def main():
    src, outp = sys.argv[1:]
    patch = [HEADER.encode()]
    for f in ("symbols.dic", "emojis.dic"):
        rel = "locale/ru/" + f
        old = open(os.path.join(src, rel), "rb").read()
        new, n = edit(os.path.join(src, rel), f == "emojis.dic")
        print(f, n, "lines", file=sys.stderr)
        a = old.split(b"\n")
        b = new.split(b"\n")
        a = [x + b"\n" for x in a[:-1]] + ([a[-1]] if a[-1] else [])
        b = [x + b"\n" for x in b[:-1]] + ([b[-1]] if b[-1] else [])
        for line in difflib.diff_bytes(difflib.unified_diff, a, b,
                                       b"a/" + rel.encode(), b"b/" + rel.encode(), n=3):
            patch.append(line)
    open(outp, "wb").write(b"".join(patch))


main()
