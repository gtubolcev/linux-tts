#!/usr/bin/python3 -I
"""gen-pyuni.py > rn-pyuni.h: Python's str predicates and case mappings for rn-pystr.c.

Run with the oracle's Python (3.12.3, Unicode 15.0 in claude-ru-normalizr), so isalpha(),
isdigit(), lower(), casefold() & co. in the C passes match ru_normalizr exactly."""
import sys
import unicodedata

MAX = 0x110000
CPS = [cp for cp in range(MAX) if not 0xD800 <= cp < 0xE000]


def ranges(pred):
    out, start, prev = [], None, None
    for cp in CPS:
        ok = pred(chr(cp))
        if ok and start is not None and cp == prev + 1:
            prev = cp
            continue
        if start is not None:
            out.append((start, prev))
            start = None
        if ok:
            start = prev = cp
    if start is not None:
        out.append((start, prev))
    return out


def cased(c):
    return c.islower() or c.isupper() or c.istitle()


def case_ignorable(c):
    t2 = ("A" + c + "Σ").lower()[-1] == "ς"
    t1 = ("1" + c + "Σ").lower()[-1] == "ς"
    return t2 and not t1


PREDS = [
    ("ALPHA", str.isalpha), ("DECIMAL", str.isdecimal), ("DIGIT", str.isdigit),
    ("NUMERIC", str.isnumeric), ("UPPER", str.isupper), ("LOWER", str.islower),
    ("SPACE", str.isspace), ("CASED", cased), ("CASE_IGNORABLE", case_ignorable),
]
print("/* generated by gen-pyuni.py with Python %s, Unicode %s; do not edit */"
      % (sys.version.split()[0], unicodedata.unidata_version))
print("#include <stdint.h>")
for name, pred in PREDS:
    rs = ranges(pred)
    print("static const uint32_t RN_PY_%s[][2] = {" % name)
    for i in range(0, len(rs), 4):
        print("\t" + " ".join("{0x%X, 0x%X}," % r for r in rs[i:i + 4]))
    print("};")
for name, fn in (("LOWERMAP", str.lower), ("UPPERMAP", str.upper), ("FOLDMAP", str.casefold),
                 ("TITLEMAP", str.title)):
    print("static const uint32_t RN_PY_%s[][4] = {   /* cp, mapping (0-padded) */" % name)
    for cp in CPS:
        c = chr(cp)
        m = fn(c)
        if m != c:
            if len(m) > 3:
                sys.exit("%s longer than 3 for U+%04X" % (name, cp))
            print("\t{0x%X, %s}," % (cp, ", ".join("0x%X" % ord(x) for x in m.ljust(3, "\0"))))
    print("};")
# unicodedata.digit (non-ASCII) and single-character integer unicodedata.numeric >= 0
# (numerals._helpers._normalize_unicode_integer_text)
print("static const uint32_t RN_PY_DIGITMAP[][2] = {   /* cp, digit */")
for cp in CPS:
    d = unicodedata.digit(chr(cp), None)
    if cp >= 0x80 and d is not None:
        print("\t{0x%X, %d}," % (cp, d))
print("};")
print("static const struct { uint32_t cp; uint64_t v; } RN_PY_INTNUMERIC[] = {")
for cp in CPS:
    v = unicodedata.numeric(chr(cp), None)
    if v is not None and float(v).is_integer() and v >= 0:
        if not 0 <= int(v) < 2**64:
            sys.exit("numeric out of range U+%04X" % cp)
        print("\t{0x%X, %dULL}," % (cp, int(v)))
print("};")
