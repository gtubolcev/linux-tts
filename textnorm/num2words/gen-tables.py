#!/usr/bin/python3 -I
"""gen-tables.py > n2w-ru-tables.h: word tables of num2words lang_RU, expanded.

Run with the oracle's num2words (0.5.14). Each classifier entry is expanded to
[case 0..5][gender m, f, n / plural][animate, inanimate] through num2words' own
case_classifier_element, so the C code needs no knowledge of the nesting."""
import importlib.metadata

from num2words import lang_RU as R

CASES = "ngdaip"
GENDERS = "mfnp"


def expand(cls, size):
    rows = []
    for num in range(size):
        if num not in cls:
            rows.append(None)
            continue
        rows.append([[[R.case_classifier_element(cls[num], case=c, gender=g, animate=a)
                       for a in (True, False)] for g in GENDERS] for c in CASES])
    return rows


def q(s):
    return "NULL" if s is None else '"%s"' % s


def emit(name, rows):
    print("static const char *const %s[%d][6][4][2] = {" % (name, len(rows)))
    for num, r in enumerate(rows):
        if r is None:
            print("\t[%d] = {{{NULL}}}," % num)
            continue
        print("\t[%d] = {" % num)
        for c in r:
            print("\t\t{" + ", ".join("{%s, %s}" % (q(g[0]), q(g[1])) for g in c) + "},")
        print("\t},")
    print("};")


print("/* generated by gen-tables.py from num2words %s lang_RU; do not edit */"
      % importlib.metadata.version("num2words"))
for name, cls, size in [("ONES", R.ONES, 10), ("ONES_ORD", R.ONES_ORD, 10), ("TENS", R.TENS, 10),
                        ("TENS_ORD", R.TENS_ORD, 10), ("TWENTIES", R.TWENTIES, 10),
                        ("TWENTIES_ORD", R.TWENTIES_ORD, 10), ("HUNDREDS", R.HUNDREDS, 10),
                        ("HUNDREDS_ORD", R.HUNDREDS_ORD, 10),
                        ("THOUSANDS_ORD", R.THOUSANDS_ORD, 11)]:
    emit("N2W_" + name, expand(cls, size))
print("static const char *const N2W_THOUSANDS[11][6][3] = {")
for num in range(11):
    if num not in R.THOUSANDS:
        print("\t[%d] = {{NULL}}," % num)
        continue
    print("\t[%d] = {" % num + ", ".join("{%s}" % ", ".join(q(x) for x in R.get_thousands_elements(num, c))
                                         for c in CASES) + "},")
print("};")
pw = R.Num2Word_RU().pointword
print("static const char *const N2W_POINTWORD[3] = {%s};" % ", ".join(q(x) for x in pw))
