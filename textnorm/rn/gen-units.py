"""Writes rn-units.h: the unit registry of ru_normalizr (numerals/_constants.py) as C tables.

Usage (oracle Python, docker image claude-ru-normalizr): python3 -I gen-units.py RN_SRC OUT.h

The registry's indices are computed here by the registry itself, so the C lookup
(rn-units.c) only repeats UnitRegistry.resolve over sorted tables:
  exact   alias -> descriptor         (CASE_SENSITIVE_UNITS_DATA)
  folded  alias -> descriptor         (UNITS_DATA)
  fold    casefold(rstrip('.')) -> descriptor, number of semantic targets
Strings are UTF-8, sorted by code point (= byte order).
"""
import sys

sys.path.insert(0, sys.argv[1])
from ru_normalizr.numerals import _constants as C  # noqa: E402

reg = C.UNIT_REGISTRY
descs: list = []
index: dict = {}


def did(d) -> int:
    key = d   # frozen dataclasses: equal descriptors share one row
    if key not in index:
        index[key] = len(descs)
        descs.append(d)
    return index[key]


def cstr(s) -> str:
    if s is None:
        return "NULL"
    out = '"'
    for b in s.encode():
        ch = chr(b)
        if ch in '"\\':
            out += "\\" + ch
        elif 32 <= b < 127:
            out += ch
        else:
            out += "\\%03o" % b
    return out + '"'


exact = sorted((a.encode(), did(d)) for a, d in reg._exact.items())
folded = sorted((a.encode(), did(d)) for a, d in reg._folded.items())
fold = sorted(
    (k.encode(), did(d), len(reg._folded_semantics.get(k, ())))
    for k, d in reg._folded_index.items()
)

with open(sys.argv[2], "w") as f:
    f.write("/* generated by gen-units.py from ru_normalizr numerals/_constants.py */\n")
    f.write("static const rn_unit RN_UNITS[] = {\n")
    for d in descs:
        m = d.morphology
        par = ";".join(f"{c} {n} {w}" for c, n, w in m.paradigm)
        f.write(
            "\t{%s, %s, %s, %s, {%s, %s, %d, %s, %s, %s, %s, %d, %d}},\n"
            % (
                cstr(d.lemma), cstr(d.gender), cstr(d.category), cstr(d.suffix),
                cstr(m.expected_normal_form), cstr(m.animacy), m.indeclinable,
                cstr(" ".join(sorted(m.preferred_grammemes))),
                cstr(" ".join(sorted(m.forbidden_grammemes))),
                cstr(m.morphology_seed), cstr(par), m.plural_only, m.byte_family,
            )
        )
    f.write("};\n")
    for name, rows in (("RN_UNITS_EXACT", exact), ("RN_UNITS_FOLDED", folded)):
        f.write(f"static const rn_unit_alias {name}[] = {{\n")
        for a, i in rows:
            f.write(f"\t{{{cstr(a.decode())}, {i}}},\n")
        f.write("};\n")
    f.write("static const rn_unit_fold RN_UNITS_FOLD[] = {\n")
    for a, i, n in fold:
        f.write(f"\t{{{cstr(a.decode())}, {i}, {n}}},\n")
    f.write("};\n")
print(len(descs), "descriptors,", len(exact), "exact,", len(folded), "folded,", len(fold), "fold keys")
