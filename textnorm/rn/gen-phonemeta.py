"""Dump the phonenumbers metadata that rn-phone.c needs (run in the oracle's Python).

python3 -I gen-phonemeta.py OUT.h

Only what parse("+digits"), is_valid_number() and INTERNATIONAL/E164 formatting read:
per calling code its regions (main first), per region the number descs, the national
prefix for parsing and the formats used for INTERNATIONAL. Patterns are kept as written
(they are ASCII digit patterns that PCRE2 reads as Python does) and stored once each.
"""
import sys

import phonenumbers
from phonenumbers import PhoneMetadata
from phonenumbers.phonenumberutil import COUNTRY_CODE_TO_REGION_CODE

DESCS = ("general_desc", "premium_rate", "toll_free", "shared_cost", "voip",
         "personal_number", "pager", "uan", "voicemail", "fixed_line", "mobile")

pats = {}


def pat(p):
    if p is None or p == "":
        return -1
    if p not in pats:
        pats[p] = len(pats)
    return pats[p]


def cstr(s):
    if s is None:
        return "NULL"
    assert all(32 <= ord(c) < 127 for c in s), s
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def mask(lengths):
    m = 0
    for n in lengths:
        assert 0 < n < 32
        m |= 1 << n
    return m


metas, fmts, ccs = [], [], []
for cc in sorted(COUNTRY_CODE_TO_REGION_CODE):
    regions = COUNTRY_CODE_TO_REGION_CODE[cc]
    first = len(metas)
    for region in regions:
        if region == "001":
            assert len(regions) == 1
            md = PhoneMetadata.metadata_for_nongeo_region(cc, None)
        else:
            md = PhoneMetadata.metadata_for_region(region, None)
        assert md is not None and md.country_code == cc, (cc, region)
        assert md.general_desc.possible_length, region
        npp = md.national_prefix_for_parsing or None
        npt = md.national_prefix_transform_rule or None
        if npt:
            import re
            assert re.compile(npp).groups > 0, region
        descs = []
        for name in DESCS:
            d = getattr(md, name)
            if d is None:
                descs.append((-1, 0, 0))
            else:
                descs.append((pat(d.national_number_pattern), mask(d.possible_length),
                              mask(d.possible_length_local_only or ())))
        avail = md.intl_number_format if len(md.intl_number_format) else md.number_format
        f0 = len(fmts)
        for f in avail:
            ld = f.leading_digits_pattern[-1] if len(f.leading_digits_pattern) else None
            fmts.append((pat(f.pattern), cstr(f.format), pat(ld)))
        metas.append((cc, region, pat(md.leading_digits), pat(npp), cstr(npt),
                      int(bool(md.same_mobile_and_fixed_line_pattern)), descs, f0,
                      len(fmts) - f0))
    ccs.append((cc, first, len(metas) - first))

src = [None] * len(pats)
for p, i in pats.items():
    src[i] = p

with open(sys.argv[1], "w") as out:
    w = out.write
    w(f"/* generated by gen-phonemeta.py from phonenumbers {phonenumbers.__version__} */\n")
    w(f"#define PN_NPATS {len(src)}\n")
    w("static const char *const pn_pat_src[PN_NPATS] = {\n")
    for p in src:
        w(f"\t{cstr(p)},\n")
    w("};\n")
    w("static const struct pn_fmt pn_fmts[] = {\n")
    for p, f, ld in fmts:
        w(f"\t{{{p}, {f}, {ld}}},\n")
    w("};\n")
    w("static const struct pn_meta pn_metas[] = {\n")
    for cc, region, ld, npp, npt, same, descs, f0, nf in metas:
        d = ", ".join(f"{{{p}, {m:#x}, {l:#x}}}" for p, m, l in descs)
        w(f"\t{{{cc}, {ld}, {npp}, {npt}, {same}, {{{d}}}, {f0}, {nf}}}, /* {region} */\n")
    w("};\n")
    w("static const struct pn_cc pn_ccs[] = {\n")
    for cc, first, n in ccs:
        w(f"\t{{{cc}, {first}, {n}}},\n")
    w("};\n")
